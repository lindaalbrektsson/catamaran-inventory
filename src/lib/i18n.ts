export function dictionary(locale: Locale) {
  return locale === 'es' ? es : en;
}
export function number(value: number, locale: Locale) {
  return new Intl.NumberFormat(locale === 'es' ? 'es-BZ' : 'en-BZ', {
    maximumFractionDigits: 3,
  }).format(value);
}
export function dateTime(value: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale === 'es' ? 'es-BZ' : 'en-BZ', {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: 'America/Belize',
  }).format(new Date(value));
}
